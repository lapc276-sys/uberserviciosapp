"""Postgres access. The tables are Prisma's (prisma/schema.prisma): quoted
CamelCase names, camelCase columns, ids generated by the writer."""

from __future__ import annotations

import json
import uuid
from typing import Any
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

import psycopg
from psycopg.rows import dict_row
from psycopg.types.json import Jsonb

# Options in a Prisma connection string that libpq does not understand.
PRISMA_ONLY = {"schema", "connection_limit", "pool_timeout", "pgbouncer", "socket_timeout", "statement_cache_size"}


def libpq_url(url: str) -> tuple[str, str | None]:
    """A Prisma URL as libpq accepts it, and the schema it named, if any."""
    parts = urlsplit(url)
    query = parse_qsl(parts.query, keep_blank_values=True)
    schema = next((value for key, value in query if key == "schema"), None)
    kept = [(key, value) for key, value in query if key not in PRISMA_ONLY]
    return urlunsplit(parts._replace(query=urlencode(kept))), schema


def connect(url: str) -> psycopg.Connection[dict[str, Any]]:
    clean, schema = libpq_url(url)
    # UTC, because Prisma stores DateTime as UTC in columns without a time
    # zone; a session in another zone would shift every default by hours.
    options = "-c timezone=UTC"
    if schema:
        if not schema.replace("_", "").isalnum():
            raise ValueError(f"unexpected schema name: {schema!r}")
        options += f" -c search_path={schema}"
    return psycopg.connect(clean, row_factory=dict_row, autocommit=True, options=options)


def new_id(prefix: str = "pl") -> str:
    """Ids for rows the pipeline writes. Prisma's are cuids; these are told apart by the prefix."""
    return f"{prefix}{uuid.uuid4().hex[:23]}"


def jsonb(value: Any) -> Jsonb | None:
    return None if value is None else Jsonb(value)


def canonical(value: Any) -> str:
    """One spelling per value, for comparing JSON details."""
    return json.dumps(value, sort_keys=True, separators=(",", ":"), default=str)
