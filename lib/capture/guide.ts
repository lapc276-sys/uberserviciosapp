export const SPACE_BY_KEY = new Map(SPACE_TEMPLATES.map((s) => [s.key, s]));

/** How many of each space the person picked, e.g. `{ kitchen: 1, bathroom: 2 }`. */
export type SpaceSelection = Record<string, number>;

export interface CaptureStep {
  /** Stable within a plan; used as a React key and for skip bookkeeping. */
  id: string;
  spaceKey: string;
  roomType: RoomType;
  /** "Baño 2" when there is more than one, "Baño" when there is one. */
  spaceLabel: string;
  title: string;
  spoken: string;
  optional: boolean;
}

/**
 * The ceiling on frames in one walkthrough.
 *
 * Bounded by the request size limit, not by the model: the shared encode
 * budget divides 3.8MB across however many frames are planned, so more frames
 * means smaller frames, and past roughly two dozen the images get too soft to
 * judge grout by. That is the real limit, so it is the one written down.
 */
export const MAX_GUIDED_FRAMES = 24;

/** A person can only hold a phone up for so long. Four spaces is already ~3 min. */
export const MAX_SPACES = 8;

export interface CapturePlan {
  steps: CaptureStep[];
  /**
   * Optional steps dropped to fit `MAX_GUIDED_FRAMES`.
   *
   * Surfaced rather than silently applied, because someone who selected a
   * whole house should be told their oven interiors were cut, not left to
   * wonder why the app skipped them.
   */
  droppedOptional: number;
  /** True when even the required steps don't fit — the selection is too big. */
  tooManySpaces: boolean;
}

/**
 * Expands a selection of spaces into the ordered list of instructions.
 *
 * Order matters and is not alphabetical: kitchens and bathrooms carry most of
 * the labour and most of the variance, so they are filmed first. If someone
 * gives up halfway through — which happens — the frames already captured are
 * the ones worth having.
 */
export function buildPlan(selection: SpaceSelection): CapturePlan {
  const ordered = SPACE_TEMPLATES.filter((t) => (selection[t.key] ?? 0) > 0);
  const steps: CaptureStep[] = [];

  for (const template of ordered) {
    const count = Math.min(selection[template.key] ?? 0, MAX_SPACES);
    for (let n = 1; n <= count; n++) {
      const spaceLabel = count > 1 ? `${template.label} ${n}` : template.label;
      const spaceKey = `${template.key}-${n}`;

      for (const [i, step] of template.steps.entries()) {
        steps.push({
          id: `${spaceKey}-${i}`,
          spaceKey,
          roomType: template.roomType,
          spaceLabel,
          title: step.title,
          spoken: step.spoken,
          optional: step.optional ?? false,
        });
      }
    }
  }

  if (steps.length <= MAX_GUIDED_FRAMES) {
    return { steps, droppedOptional: 0, tooManySpaces: false };
  }

  // Trim optional steps from the end first. The spaces filmed last are the
  // ones the estimate depends on least, so their detail shots are the cheapest
  // thing to lose.
  const kept = [...steps];
  let dropped = 0;
  for (let i = kept.length - 1; i >= 0 && kept.length > MAX_GUIDED_FRAMES; i--) {
    if (kept[i].optional) {
      kept.splice(i, 1);
      dropped += 1;
    }
  }

  return {
    steps: kept.slice(0, MAX_GUIDED_FRAMES),
    droppedOptional: dropped,
    tooManySpaces: kept.length > MAX_GUIDED_FRAMES,
  };
}

/** Roughly how long the walkthrough will take, for the "listo?" screen. */
export function estimateWalkSeconds(stepCount: number): number {
  // ~8s per step in testing: hear the instruction, move, aim, shoot.
  return stepCount * 8;
}

/**
 * The caption sent to the model alongside each frame.
 *
 * `spaceKey` is the load-bearing part, not the prose: it is what tells the
 * model that frames 3 and 4 are the same bathroom rather than two of them,
 * which is the single biggest source of wrong room counts. The Spanish title
 * rides along as description; the room type is repeated in English so the
 * model has the vocabulary the rest of the prompt uses.
 */
export function captionFor(step: CaptureStep): string {
  return `[${step.spaceKey}] ${step.roomType} — ${step.title} (${step.spaceLabel})`;
}
