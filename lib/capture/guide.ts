import type { RoomType } from '@/lib/vision/types';
import type { Lang } from './lang';

/**
 * The script the app reads out loud during a walkthrough.
 *
 * Sampling a video on a timer produces whatever the camera happened to be
 * pointed at — mostly hallways and ceilings, because that is what you film
 * while walking. The frames that decide a price are the ones nobody films
 * without being asked: inside the microwave, behind the toilet, the grout in
 * the shower, the floor under the cabinets. A cleaner knows to look there. A
 * homeowner recording their own kitchen does not.
 *
 * So the app asks. One instruction, one frame, next instruction. That buys
 * three things at once:
 *
 *   1. Better evidence. Every frame is aimed at something that carries time.
 *   2. Far less data. Twenty deliberate frames beat two minutes of video, and
 *      the request stays inside the size limit by construction rather than by
 *      luck.
 *   3. A caption per frame. The model is told "this is the kitchen sink"
 *      instead of inferring it, which is where double-counted rooms come from.
 *
 * The list is fixed rather than generated by a model between steps. A model in
 * the loop would add a round trip and a failure mode to every single step, in
 * a stranger's kitchen, on a phone with one bar. The questions worth asking
 * about a kitchen do not change from house to house; what varies is the
 * answer, and the answer is the photograph.
 */

/**
 * How a step decides it has what it needs.
 *
 * `settle` waits for the view to change and then hold still — someone aiming
 * at a sink, or swinging a fridge door open and steadying the phone. One frame.
 *
 * `pan` samples across a slow sweep and keeps the most different frames, so an
 * overview of a kitchen covers the room instead of photographing one cupboard
 * three times.
 */
export type StepMode = 'settle' | 'pan';

/** What a step says, in one language. */
export interface StepWords {
  title: string;
  spoken: string;
  after?: string;
}

export interface StepTemplate {
  /**
   * Short label shown on screen and used as the frame's caption.
   *
   * The caption is always this Spanish title, whatever language the person
   * walks in: it is read by the model, whose prompt describes captions in
   * Spanish, and two caption languages would be two ways to describe one
   * oven to the thing that prices it.
   */
  title: string;
  /** Read aloud. Written as an instruction to a person holding a phone. */
  spoken: string;
  /**
   * Said once the shot is taken. Only where the person is left holding
   * something open — nobody should have to guess when they can close the oven.
   */
  after?: string;
  /** The same step in English. Written, not machine-translated. */
  en: StepWords;
  mode?: StepMode;
  /** How many frames a `pan` step keeps. Ignored by `settle`. */
  frames?: number;
  /**
   * Skippable with "no tengo".
   *
   * Not every home has an oven, and being unable to move past a question about
   * one is how a walkthrough gets abandoned halfway.
   */
  optional?: boolean;
  /**
   * Kept when this space has to be cut down to fit a big home into one walk.
   *
   * The overview pan is always kept — it is the only frame of the whole room,
   * and the one the room's questions are built from — so this marks the one
   * close-up worth keeping beside it.
   */
  core?: boolean;
}

export interface SpaceTemplate {
  key: string;
  roomType: RoomType;
  /** Spanish: also the name the company reads in notes and messages. */
  label: string;
  labelEn: string;
  emoji: string;
  steps: StepTemplate[];
  /**
   * Never cut down to make room.
   *
   * Kitchens and bathrooms carry most of the labour and most of the variance
   * between homes, so they keep every shot. A closet is here for the opposite
   * reason: its shots are only worth anything as a set — closed, open, top,
   * bottom — and half of that set prices nothing.
   */
  keepWhole?: boolean;
}

