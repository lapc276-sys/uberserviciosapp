export const SPACE_BY_KEY = new Map(SPACE_TEMPLATES.map((s) => [s.key, s]));

/** How many of each space the person picked, e.g. `{ kitchen: 1, bathroom: 2 }`. */
export type SpaceSelection = Record<string, number>;

export interface CaptureStep {
  /** Stable within a plan; used as a React key and for skip bookkeeping. */
  id: string;
  spaceKey: string;
  roomType: RoomType;
  /** "Baño 2" when there is more than one, "Baño" when there is one. */
  spaceLabel: string;
  title: string;
  spoken: string;
  after?: string;
  /** The same step in English, with its space named in English ("Bathroom 2"). */
  en: StepWords & { spaceLabel: string };
  mode: StepMode;
  /** Frames this step contributes. 1 for `settle`, more for a pan. */
  frames: number;
  optional: boolean;
  /**
   * Added at the review by the customer pointing at something the walkthrough
   * missed ("¿me salté algo?"). Not part of any plan; see GuidedCapture.
   */
  pointed?: boolean;
}

/** A step's words in the walkthrough's language. Spanish fields are the canonical ones. */
export function wordsFor(step: CaptureStep, lang: Lang): StepWords & { spaceLabel: string } {
  // A plan replayed from before English existed has no `en`; Spanish is the
  // honest fallback rather than a crash halfway through an "after" pass.
  if (lang === 'en' && step.en) return step.en;
  return { title: step.title, spoken: step.spoken, after: step.after, spaceLabel: step.spaceLabel };
}

/** A space's name in both languages, for the planning screen's notes. */
export interface SpaceName {
  es: string;
  en: string;
}

/**
 * The ceiling on frames in one walkthrough.
 *
 * Bounded by the request size limit, not by the model: the shared encode
 * budget (TOTAL_BUDGET_CHARS in lib/vision/frames.ts) is divided across however
 * many frames are planned, so more frames means smaller frames. At 36 each gets
 * about 55K characters — roughly 1.7 bits per pixel at the 512px the model
 * actually looks at, which is still a clean JPEG. Past that the images start
 * getting too soft to judge grout by.
 *
 * It was 24 while frames were encoded at 768px, and 24 does not hold an
 * ordinary two-bedroom apartment: the planner used to fit one by filming the
 * kitchen, both bathrooms and one bedroom, and quietly not filming the rest.
 */
export const MAX_GUIDED_FRAMES = 36;

/** A person can only hold a phone up for so long. Four spaces is already ~3 min. */
export const MAX_SPACES = 8;

export interface CapturePlan {
  steps: CaptureStep[];
  /**
   * Spaces cut down to their overview pan plus one close-up, to fit.
   *
   * The first thing given up, because a bedroom's pan already shows most of
   * what a bedroom costs, and the alternative is losing a whole room.
   */
  lightened: SpaceName[];
  /**
   * Optional steps dropped to fit `MAX_GUIDED_FRAMES`.
   *
   * Surfaced rather than silently applied, because someone who selected a
   * whole house should be told their oven interiors were cut, not left to
   * wonder why the app skipped them.
   */
  droppedOptional: number;
  /**
   * Whole spaces that still did not fit, by name.
   *
   * Never silent. A room that is not filmed is a room the model never sees,
   * and a room the model never sees is a room the price does not charge for —
   * the customer is quoted for a smaller home than the one the crew walks into.
   */
  droppedSpaces: SpaceName[];
  /** True when any whole space was left out. */
  tooManySpaces: boolean;
}

/** One step plus what the trimmer needs to know about it. */
interface Planned {
  step: CaptureStep;
  /** Survives its space being cut down. */
  keep: boolean;
  /** The space it belongs to may be cut down at all. */
  trimmable: boolean;
}

/**
 * Expands a selection of spaces into the ordered list of instructions.
 *
 * Order matters and is not alphabetical: kitchens and bathrooms carry most of
 * the labour and most of the variance, so they are filmed first. If someone
 * gives up halfway through — which happens — the frames already captured are
 * the ones worth having.
 *
 * When the home is too big for one walk, it is shortened in this order, each
 * stage only as far as needed:
 *
 *   1. Secondary spaces (bedrooms, living, dining…) are cut to their pan plus
 *      one close-up, starting with the last one filmed.
 *   2. Optional detail shots go, from the end.
 *   3. Whole spaces go, from the end — and are named on the planning screen.
 *
 * Every space is kept, even if lighter, before any space is lost.
 */
export function buildPlan(selection: SpaceSelection): CapturePlan {
  const ordered = SPACE_TEMPLATES.filter((t) => (selection[t.key] ?? 0) > 0);
  let planned: Planned[] = [];

  for (const template of ordered) {
    const count = Math.min(selection[template.key] ?? 0, MAX_SPACES);
    for (let n = 1; n <= count; n++) {
      const spaceLabel = count > 1 ? `${template.label} ${n}` : template.label;
      const spaceLabelEn = count > 1 ? `${template.labelEn} ${n}` : template.labelEn;
      const spaceKey = `${template.key}-${n}`;

      for (const [i, step] of template.steps.entries()) {
        const mode = step.mode ?? 'settle';
        planned.push({
          step: {
            id: `${spaceKey}-${i}`,
            spaceKey,
            roomType: template.roomType,
            spaceLabel,
            title: step.title,
            spoken: step.spoken,
            after: step.after,
            en: { ...step.en, spaceLabel: spaceLabelEn },
            mode,
            frames: mode === 'pan' ? (step.frames ?? 2) : 1,
            optional: step.optional ?? false,
          },
          keep: mode === 'pan' || Boolean(step.core),
          trimmable: !template.keepWhole,
        });
      }
    }
  }

  // The cap is on frames, not on steps: a pan contributes several, so counting
  // steps would let an eight-room plan sail past the limit it is meant to hold.
  const frames = (list: Planned[]) => list.reduce((sum, p) => sum + p.step.frames, 0);
  const fits = () => frames(planned) <= MAX_GUIDED_FRAMES;

  if (fits()) {
    return { steps: planned.map((p) => p.step), lightened: [], droppedOptional: 0, droppedSpaces: [], tooManySpaces: false };
  }

  const labels = new Map<string, SpaceName>(
    planned.map((p) => [p.step.spaceKey, { es: p.step.spaceLabel, en: p.step.en.spaceLabel }]),
  );
  const spaces = [...labels.keys()];

  // 1. Cut secondary spaces down, the last one filmed first.
  const lightened: string[] = [];
  for (const key of [...spaces].reverse()) {
    if (fits()) break;
    const cut = planned.filter((p) => p.step.spaceKey === key && p.trimmable && !p.keep);
    if (cut.length === 0) continue;
    planned = planned.filter((p) => !cut.includes(p));
    lightened.unshift(key);
  }

  // 2. Optional detail shots, from the end.
  let droppedOptional = 0;
  for (let i = planned.length - 1; i >= 0 && !fits(); i--) {
    if (planned[i].step.optional) {
      planned.splice(i, 1);
      droppedOptional += 1;
    }
  }

  // 3. Whole spaces, from the end. A space goes entirely or not at all: half a
  // bathroom is a bathroom the model scores from the wrong evidence.
  const dropped: string[] = [];
  while (planned.length > 0 && !fits()) {
    const last = planned[planned.length - 1].step.spaceKey;
    dropped.unshift(last);
    planned = planned.filter((p) => p.step.spaceKey !== last);
  }

  return {
    steps: planned.map((p) => p.step),
    // A space cut down and then dropped anyway is reported once, as dropped.
    lightened: lightened.filter((key) => !dropped.includes(key)).map((key) => labels.get(key)!),
    droppedOptional,
    droppedSpaces: dropped.map((key) => labels.get(key)!),
    tooManySpaces: dropped.length > 0,
  };
}

/** "A", "A y B", "A, B y C" — or "A, B and C". */
export function joinList(items: string[], lang: Lang = 'es'): string {
  if (items.length <= 1) return items[0] ?? '';
  return `${items.slice(0, -1).join(', ')} ${lang === 'en' ? 'and' : 'y'} ${items[items.length - 1]}`;
}

/** Kept for callers that only ever spoke Spanish. */
export function joinEs(items: string[]): string {
  return joinList(items, 'es');
}

/**
 * What the planning screen says about a shortened walk, or null when nothing
 * was shortened. Spelled out per space, because "dejaré fuera 6 tomas" was the
 * sentence that hid three missing rooms.
 */
export function shortenedNote(plan: CapturePlan, lang: Lang = 'es'): string | null {
  const names = joinList(plan.lightened.map((s) => s[lang]), lang);
  const n = plan.droppedOptional;
  const parts: string[] = [];
  if (lang === 'en') {
    if (plan.lightened.length) parts.push(`in ${names} I will only do the sweep and one close-up`);
    if (n > 0) parts.push(`I will leave out ${n} detail ${n === 1 ? 'shot' : 'shots'} (inside the oven, the trash and similar)`);
    return parts.length ? `To keep it short, ${parts.join(', and ')}.` : null;
  }
  if (plan.lightened.length) parts.push(`en ${names} solo haré el paneo y una foto de cerca`);
  if (n > 0) parts.push(`dejaré fuera ${n} ${n === 1 ? 'toma' : 'tomas'} de detalle (dentro del horno, la basura y parecidos)`);
  return parts.length ? `Para que no se haga largo, ${parts.join(', y ')}.` : null;
}

/** The warning for spaces that do not fit at all, or null when everything does. */
export function droppedNote(plan: CapturePlan, lang: Lang = 'es'): string | null {
  if (!plan.droppedSpaces.length) return null;
  const names = joinList(plan.droppedSpaces.map((s) => s[lang]), lang);
  const one = plan.droppedSpaces.length === 1;
  if (lang === 'en') {
    return `Not everything fits in one walkthrough: ${names} would not be filmed, and the price would not count ${one ? 'it' : 'them'}. Remove ${one ? 'that space' : 'those spaces'} from the list and do ${one ? 'it' : 'them'} in a second walkthrough.`;
  }
  const these = one ? 'ese espacio' : 'esos espacios';
  return `No cabe todo en un recorrido: se quedarían sin filmar ${names}, y el precio no los contaría. Quita ${these} de la lista y hazlos en un segundo recorrido.`;
}

/** Total frames a plan will produce, which is what the size budget divides. */
export function planFrameCount(steps: CaptureStep[]): number {
  return steps.reduce((sum, s) => sum + s.frames, 0);
}

/** Roughly how long the walkthrough will take, for the planning screen. */
export function estimateWalkSeconds(steps: CaptureStep[]): number {
  // ~9s per step: hear the instruction, walk to it, aim, hold still. A pan
  // runs longer because the sweep itself has to be slow enough to stay sharp.
  return steps.reduce((sum, s) => sum + (s.mode === 'pan' ? 14 : 9), 0);
}

/**
 * The caption sent to the model alongside each frame.
 *
 * `spaceKey` is the load-bearing part, not the prose: it is what tells the
 * model that frames 3 and 4 are the same bathroom rather than two of them,
 * which is the single biggest source of wrong room counts. The Spanish title
 * rides along as description; the room type is repeated in English so the
 * model has the vocabulary the rest of the prompt uses.
 */
export function captionFor(step: CaptureStep): string {
  return `[${step.spaceKey}] ${step.roomType} — ${step.title} (${step.spaceLabel})`;
}
