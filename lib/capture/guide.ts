import type { RoomType } from '@/lib/vision/types';

/**
 * The script the app reads out loud during a walkthrough.
 *
 * Sampling a video on a timer produces whatever the camera happened to be
 * pointed at — mostly hallways and ceilings, because that is what you film
 * while walking. The frames that decide a price are the ones nobody films
 * without being asked: inside the microwave, behind the toilet, the grout in
 * the shower, the floor under the cabinets. A cleaner knows to look there. A
 * homeowner recording their own kitchen does not.
 *
 * So the app asks. One instruction, one frame, next instruction. That buys
 * three things at once:
 *
 *   1. Better evidence. Every frame is aimed at something that carries time.
 *   2. Far less data. Twenty deliberate frames beat two minutes of video, and
 *      the request stays inside the size limit by construction rather than by
 *      luck.
 *   3. A caption per frame. The model is told "this is the kitchen sink"
 *      instead of inferring it, which is where double-counted rooms come from.
 *
 * The list is fixed rather than generated by a model between steps. A model in
 * the loop would add a round trip and a failure mode to every single step, in
 * a stranger's kitchen, on a phone with one bar. The questions worth asking
 * about a kitchen do not change from house to house; what varies is the
 * answer, and the answer is the photograph.
 */

export interface StepTemplate {
  /** Short label shown on screen and used as the frame's caption. */
  title: string;
  /** Read aloud. Written as an instruction to a person holding a phone. */
  spoken: string;
  /**
   * Skippable with "no tengo".
   *
   * Not every home has an oven, and being unable to move past a question about
   * one is how a walkthrough gets abandoned halfway.
   */
  optional?: boolean;
}

export interface SpaceTemplate {
  key: string;
  roomType: RoomType;
  /** Spanish, because the person holding the phone is reading this. */
  label: string;
  emoji: string;
  steps: StepTemplate[];
}

